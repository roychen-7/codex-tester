CREATE TABLE IF NOT EXISTS analysis_runs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 conversation_id BIGINT UNSIGNED NOT NULL,
 task_id BIGINT UNSIGNED NOT NULL,
 task_revision INT UNSIGNED NOT NULL,
 attempt_no INT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL,
 phase VARCHAR(40) NOT NULL,
 model VARCHAR(128) NOT NULL,
 skill_version VARCHAR(64) NOT NULL,
 context_snapshot JSON NOT NULL,
 answer JSON NULL,
 assistant_message_id BIGINT UNSIGNED NULL,
 error_message VARCHAR(1000) NULL,
 started_at DATETIME(6) NULL,
 finished_at DATETIME(6) NULL,
 deadline_at DATETIME(6) NOT NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 active_conversation_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status IN ('pending','running') THEN conversation_id ELSE NULL END) STORED,
 PRIMARY KEY (id),
 UNIQUE KEY uq_analysis_attempt (task_id,task_revision,attempt_no),
 UNIQUE KEY uq_analysis_active (active_conversation_id),
 UNIQUE KEY uq_analysis_message (assistant_message_id),
 KEY idx_analysis_recent (conversation_id,id DESC),
 KEY idx_analysis_queue (status,deadline_at),
 CONSTRAINT fk_analysis_conversation FOREIGN KEY (conversation_id) REFERENCES conversations(id),
 CONSTRAINT fk_analysis_task FOREIGN KEY (task_id,conversation_id) REFERENCES agent_tasks(id,conversation_id),
 CONSTRAINT fk_analysis_message FOREIGN KEY (assistant_message_id,conversation_id) REFERENCES messages(id,conversation_id),
 CONSTRAINT chk_analysis_status CHECK (status IN ('pending','running','succeeded','failed','cancelled')),
 CONSTRAINT chk_analysis_revision CHECK (task_revision>0 AND attempt_no>0),
 CONSTRAINT chk_analysis_snapshot CHECK (JSON_TYPE(context_snapshot)='OBJECT'),
 CONSTRAINT chk_analysis_answer CHECK (answer IS NULL OR JSON_TYPE(answer)='OBJECT'),
 CONSTRAINT chk_analysis_terminal CHECK ((status IN ('pending','running') AND finished_at IS NULL) OR (status IN ('succeeded','failed','cancelled') AND finished_at IS NOT NULL)),
 CONSTRAINT chk_analysis_success CHECK ((status='succeeded' AND answer IS NOT NULL AND assistant_message_id IS NOT NULL) OR (status<>'succeeded' AND answer IS NULL AND assistant_message_id IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS analysis_steps (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 analysis_run_id BIGINT UNSIGNED NOT NULL,
 sequence_no INT NOT NULL,
 kind VARCHAR(20) NOT NULL,
 name VARCHAR(128) NOT NULL,
 status VARCHAR(20) NOT NULL,
 input JSON NOT NULL,
 output JSON NULL,
 provider_response_id VARCHAR(255) NULL,
 input_tokens BIGINT UNSIGNED NULL,
 output_tokens BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uq_analysis_step (analysis_run_id,sequence_no),
 CONSTRAINT fk_analysis_step_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs(id),
 CONSTRAINT chk_analysis_step_status CHECK (status IN ('running','succeeded','failed')),
 CONSTRAINT chk_analysis_step_kind CHECK (kind IN ('model','tool'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS query_results (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 analysis_run_id BIGINT UNSIGNED NOT NULL,
 result_id VARCHAR(128) NOT NULL,
 evidence JSON NOT NULL,
 created_at DATETIME(6) NOT NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uq_query_result (analysis_run_id,result_id),
 CONSTRAINT fk_query_result_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs(id),
 CONSTRAINT chk_query_evidence CHECK (JSON_TYPE(evidence)='OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
